#!/usr/bin/env python3
"""Generate kernel/mind/intent/intent.gen.{h,cpp}: what the mind's state estimate and intents know.

From the Python reference in mind/kilo/intent (docs/intent.md):

- the state estimate's table: the attitude the body model predicts for each
  upright state and its tolerance (kilo.intent.estimate.table(), computed
  here from the model: protocol/spec.toml through BodyModel and the 3-D rest
  finder), and its thresholds;
- the moves planned and checked from the model (mind/kilo/intent/moves/*.json,
  written by `python -m kilo.intent.moves --write`; that check takes a minute,
  so its result is committed and only read here), as tricks in wire form
  exactly as kernel/mind/tricks/gen_library.py encodes the library's;
- the edges (kilo.intent.graph.edges()) and the first step from every state
  to every goal (graph.next_table()).

    .venv/bin/python kernel/mind/intent/gen_intent.py           write the files
    .venv/bin/python kernel/mind/intent/gen_intent.py --check   exit 1 if stale (kernel/host/test.sh)
"""

from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
sys.path.insert(0, str(REPO / "mind"))

from kilo.body.client import trick_id_for  # noqa: E402
from kilo.intent import estimate as E  # noqa: E402
from kilo.intent import graph as G  # noqa: E402
from kilo.intent import moves as M  # noqa: E402

OUT_H = HERE / "intent.gen.h"
OUT_CPP = HERE / "intent.gen.cpp"
HEAD = ("// Generated by kernel/mind/intent/gen_intent.py from mind/kilo/intent (the body model's\n"
        "// predictions and the moves checked against it). Do not edit: change the Python (or run\n"
        "// python -m kilo.intent.moves --write) and re-run the script (kernel/host/test.sh runs it with --check).\n")

STATE_ID = {E.State.UNKNOWN: "Unknown", E.State.MOVING: "Moving", E.State.STANDING: "Standing",
            E.State.SITTING: "Sitting", E.State.RESTING: "Resting", E.State.ON_LEFT_SIDE: "OnLeftSide",
            E.State.ON_RIGHT_SIDE: "OnRightSide", E.State.ON_BACK: "OnBack", E.State.ON_END: "OnEnd"}
KIND_ID = {G.Kind.NONE: "None", G.Kind.MOVE: "Move", G.Kind.POSTURE: "Posture", G.Kind.WAIT_REFLEX: "WaitReflex"}


def a16(deg: float) -> int:
    v = abs(deg) * 16
    return int(v + 0.5) * (1 if deg >= 0 else -1)


def ident(name: str) -> str:
    return "k" + "".join(p.capitalize() for p in name.split("_"))


def render() -> tuple[str, str]:
    rows = E.table()
    edges = G.edges()
    nxt = G.next_table(edges)
    names = M.shipped()
    mask = 0
    for m in E.MOVING_MODES:
        mask |= 1 << m
    h = [HEAD.rstrip("\n"), "#ifndef KILO_MIND_INTENT_INTENT_GEN_H", "#define KILO_MIND_INTENT_INTENT_GEN_H",
         '#include "intent/table.h"', "", "namespace kilo {", "namespace intent {", "",
         "// kilo.intent.estimate's constants",
         f"constexpr int16_t kStillA16 = {E.STILL_DPS * 16};      // every rate under this (a16/s): still",
         f"constexpr uint64_t kStillUs = {E.STILL_US};     // ...for this long: settled",
         f"constexpr uint64_t kConfirmUs = {E.CONFIRM_US};   // a new answer holds this long before it is the state",
         f"constexpr int16_t kEndA16 = {E.END_DEG * 16};        // |pitch| folded about 90 deg at least this: ON_END",
         f"constexpr int16_t kSideA16 = {E.SIDE_DEG * 16};       // |roll| from here: on a side",
         f"constexpr int16_t kBackA16 = {E.BACK_DEG * 16};      // ...past here: on the back",
         f"constexpr uint16_t kMovingModes = 0x{mask:04X};  // bit m: the body's mode m is a moving one", "",
         f"constexpr int kRowCount = {len(rows)};",
         "// The upright states as the body model predicts them (TELEMETRY's a16) and their tolerance.",
         "extern const Row kRows[kRowCount];", "",
         f"constexpr int kMoveCount = {len(names)};",
         "// The moves planned and checked from the model (mind/kilo/intent/moves/), as tricks.",
         f"extern const tricks::Trick kMoves[{max(len(names), 1)}];",
         "// What Python computes for each kMoves entry, for the tests (as tricks::TrickCheck).",
         "struct MoveCheck {", "  uint16_t crc16;", "  uint8_t trick_id;", "  uint16_t total_ticks;", "};",
         f"extern const MoveCheck kMoveCheck[{max(len(names), 1)}];", "",
         f"constexpr int kEdgeCount = {len(edges)};",
         "extern const Edge kEdges[kEdgeCount];",
         "// The first step from a state (row, State order) to a goal (column: Standing, Sitting, Resting):",
         "// an index into kEdges, -1 for none (already there, moving, or no way).",
         "extern const int8_t kNext[kStates][kGoals];", "",
         "}  // namespace intent", "}  // namespace kilo", "", "#endif"]
    c = [HEAD.rstrip("\n"), '#include "intent/intent.gen.h"', "", "namespace kilo {", "namespace intent {", "",
         "namespace {", ""]
    trows, checks = [], []
    for name in names:
        t = M.load_move(name).validate()
        b = t.begin(0)
        n = len(t.frames)
        src = t.source
        c.append(f"// {name}: {n} frame{'s' if n != 1 else ''}, end {t.end_posture.name}; "
                 f"margin {min(src['margin_mm'].values()):.1f} mm, {src['dynamics']['bands']} bands of the dynamics")
        c.append(f"const kilo_keyframe_t {ident(name)}[] = {{")
        for f in t.frames:
            w = f.to_wire()
            c.append(f"    {{{w.dur}, {w.hold}, 0x{w.flags:02X}, {{{', '.join(str(a) for a in w.ang)}}}}},")
        c.append("};")
        trows.append(f'    {{"{t.name}", "", {b.n_frames}, {b.loop_start}, {b.loop_end}, {b.repeats}, '
                     f"0x{b.joint_mask:04X}, 0x{b.flags:02X}, {b.end_posture}, {b.exp_roll}, {b.exp_pitch}, "
                     f"{ident(name)}, {t.stop_ticks}, nullptr, 0, {a16(t.roll_max)}}},")
        checks.append(f"    {{0x{t.crc16():04X}, {trick_id_for(t)}, {t.duration_ticks or 0}}},  // {name}")
    if not names:
        trows.append('    {"", "", 0, 0, 0, 0, 0, 0, 0, 0, 0, nullptr, 0, nullptr, 0, 0},')
        checks.append("    {0, 0, 0},")
    c += ["", "}  // namespace", "", "const Row kRows[kRowCount] = {"]
    for r in rows:
        c.append(f"    {{State::{STATE_ID[r.state]}, {r.pitch}, {r.roll}, {r.tol_pitch}, {r.tol_roll}}},  "
                 f"// pitch {r.pitch / 16:+.1f} roll {r.roll / 16:+.1f} deg, +-{r.tol_pitch / 16:.1f} / "
                 f"{r.tol_roll / 16:.1f}; the model: margin {r.margin_mm} mm on {', '.join(r.contacts)}")
    c += ["};", "", f"const tricks::Trick kMoves[{max(len(names), 1)}] = {{", *trows, "};", "",
          f"const MoveCheck kMoveCheck[{max(len(names), 1)}] = {{", *checks, "};", "",
          "const Edge kEdges[kEdgeCount] = {"]
    for i, e in enumerate(edges):
        mv = f"&kMoves[{names.index(e.move)}]" if e.kind == G.Kind.MOVE else "nullptr"
        c.append(f"    {{State::{STATE_ID[e.src]}, State::{STATE_ID[e.dst]}, EdgeKind::{KIND_ID[e.kind]}, {mv}, "
                 f"{e.posture}}},  // {i}")
    c += ["};", "", "const int8_t kNext[kStates][kGoals] = {"]
    for s in E.State:
        c.append("    {" + ", ".join(str(v) for v in nxt[int(s)]) + "},  // " + s.name)
    c += ["};", "", "}  // namespace intent", "}  // namespace kilo"]
    return "\n".join(h) + "\n", "\n".join(c) + "\n"


def main(argv: list[str]) -> int:
    h, cpp = render()
    stale = [p for p, text in ((OUT_H, h), (OUT_CPP, cpp)) if not p.exists() or p.read_text() != text]
    if "--check" in argv:
        if stale:
            print("stale (run kernel/mind/intent/gen_intent.py):", *(str(p.relative_to(REPO)) for p in stale),
                  sep="\n  ", file=sys.stderr)
            return 1
        return 0
    for p, text in ((OUT_H, h), (OUT_CPP, cpp)):
        p.write_text(text)
    print(f"wrote {OUT_H.relative_to(REPO)}, {OUT_CPP.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
