#!/usr/bin/env python3
"""Generate kernel/mind/tricks/library.gen.{h,cpp}: the trick library compiled into the mind.

The tricks are mind/kilo/tricks/library/*.json (kilo.tricks.library, which
the legacy importer writes). The C++ mind has no filesystem at boot, so
this script encodes each of them exactly as the Python design tools see
them (kilo.tricks.model: Trick.begin() and the 14 B frames from
Keyframe.to_wire(), so the rounding and clamping are Python's) into const
tables, with the CRC-16, the trick_id and the duration Python computes,
which kernel/host/tests/test_tricks.cpp checks the C++ against. The mind's
player (tricks/player.h) sends them to the body as POSE keys.

It lives next to its output, as protocol/vendor.py does, because it is
part of the build's sources, not a test.

    .venv/bin/python kernel/mind/tricks/gen_library.py           write the files
    .venv/bin/python kernel/mind/tricks/gen_library.py --check   exit 1 if stale (kernel/host/test.sh)
"""

from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
sys.path.insert(0, str(REPO / "mind"))

from kilo.tricks.model import trick_id_for  # noqa: E402
from kilo.tricks import library  # noqa: E402

OUT_H = HERE / "library.gen.h"
OUT_CPP = HERE / "library.gen.cpp"
HEAD = ("// Generated by kernel/mind/tricks/gen_library.py from mind/kilo/tricks/library/*.json.\n"
        "// Do not edit: change the JSON (or its importer) and re-run the script\n"
        "// (kernel/host/test.sh runs it with --check).\n")


def a16(deg: float) -> int:
    """Degrees as the protocol's 1/16 deg, rounded half away from zero."""
    v = abs(deg) * 16
    return int(v + 0.5) * (1 if deg >= 0 else -1)


def ident(name: str) -> str:
    return "k" + "".join(p.capitalize() for p in name.split("_"))


def render() -> tuple[str, str, int]:
    names = library.names()
    h = [HEAD.rstrip("\n"), "#ifndef KILO_MIND_TRICKS_LIBRARY_GEN_H", "#define KILO_MIND_TRICKS_LIBRARY_GEN_H",
         '#include "tricks/model.h"', "", "namespace kilo {", "namespace tricks {", "",
         f"constexpr uint32_t kLibrarySize = {len(names)};",
         "// In kilo.tricks.library.names() order: the first version, then the authored tricks.",
         "extern const Trick kLibrary[kLibrarySize];", "",
         "// What Python computes for each kLibrary entry, for the tests.",
         "struct TrickCheck {",
         "  uint16_t crc16;        // Trick.crc16()",
         "  uint8_t trick_id;      // model.trick_id_for()",
         "  uint16_t total_ticks;  // Trick.duration_ticks at 1x (0: until stopped)",
         "};",
         "extern const TrickCheck kLibraryCheck[kLibrarySize];", "",
         "}  // namespace tricks", "}  // namespace kilo", "", "#endif"]
    c = [HEAD.rstrip("\n"), '#include "tricks/library.gen.h"', "", "namespace kilo {", "namespace tricks {", "",
         "namespace {", ""]
    rows, checks = [], []
    data_bytes = 0
    for name in names:
        t = library.load(name).validate()
        b = t.begin(0)
        legacy = library.legacy_name(name)
        n = len(t.frames)
        c.append(f"// {name} ({'legacy ' + legacy if legacy else 'authored'}): {n} frame{'s' if n != 1 else ''}, "
                 f"loop {t.loop_start}..{t.loop_end} x{t.repeats}, end {t.end_posture.name}"
                 + (f", stop over {t.stop_ticks} ticks" if t.stop_ticks else ""))
        c.append(f"const Keyframe {ident(name)}[] = {{")
        for f in t.frames:
            w = f.to_wire()
            c.append(f"    {{{w.dur}, {w.hold}, 0x{w.flags:02X}, {{{', '.join(str(a) for a in w.ang)}}}}},")
        c.append("};")
        data_bytes += len(t.frames) * 14  # Keyframe (model.h)
        guards = "nullptr, 0"
        if t.guards:
            c.append(f"const TrickGuard {ident(name)}Guards[] = {{")
            for g in t.guards:
                push = f", {a16(g.push_roll)}" if g.push_roll else ""
                c.append(f'    {{{g.frame}, {a16(g.nose_up[0])}, {a16(g.nose_up[1])}, {a16(g.roll_max)}, "{g.name}"{push}}},')
            c.append("};")
            guards = f"{ident(name)}Guards, {len(t.guards)}"
        rows.append(f'    {{"{name}", "{legacy}", {b.n_frames}, {b.loop_start}, {b.loop_end}, {b.repeats}, '
                    f"0x{b.joint_mask:04X}, 0x{b.flags:02X}, {b.end_posture}, {b.exp_roll}, {b.exp_pitch}, "
                    f"{ident(name)}, {t.stop_ticks}, {guards}, {a16(t.roll_max)}}},")
        checks.append(f"    {{0x{t.crc16():04X}, {trick_id_for(t)}, {t.duration_ticks or 0}}},  // {name}")
    data_bytes += len(names) * (3 * 4 + 13) + len(names) * 6  # kLibrary rows (3 pointers, 13 B fields) + checks
    c += ["", "}  // namespace", "", "const Trick kLibrary[kLibrarySize] = {", *rows, "};", "",
          "const TrickCheck kLibraryCheck[kLibrarySize] = {", *checks, "};", "",
          "}  // namespace tricks", "}  // namespace kilo"]
    return "\n".join(h) + "\n", "\n".join(c) + "\n", data_bytes


def main(argv: list[str]) -> int:
    h, cpp, size = render()
    stale = [p for p, text in ((OUT_H, h), (OUT_CPP, cpp)) if not p.exists() or p.read_text() != text]
    if "--check" in argv:
        if stale:
            print("stale (run kernel/mind/tricks/gen_library.py):",
                  *(str(p.relative_to(REPO)) for p in stale), sep="\n  ", file=sys.stderr)
            return 1
        return 0
    for p, text in ((OUT_H, h), (OUT_CPP, cpp)):
        p.write_text(text)
    print(f"wrote {OUT_H.relative_to(REPO)}, {OUT_CPP.relative_to(REPO)} (about {size} B of tables, "
          f"names aside, on a 32-bit target)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
