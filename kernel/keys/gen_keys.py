#!/usr/bin/env python3
"""Compile kernel/keys/authorized_keys into the kernel: a C++ header with
the laptops' public keys (kernel/mind/net/authorized_keys.h AuthorizedKey)
for src/kernel.cpp. kernel/Makefile runs it on every build; it rewrites the
header only when it changes, and fails with what to do when the list has
no key (a kernel that lets no laptop in is not worth flashing).

    python3 kernel/keys/gen_keys.py LIST OUT.h [--shown-as NAME]

The format (also read by kilo-mind-host --authorized-keys, kernel/host/posix.cpp,
and written by `kilo key show`, mind/kilo/hostkey.py): per line, the 32-byte
X25519 public key in base64 (44 characters), then optionally a name; blank
lines and lines starting with # are skipped. Standard library only (the
kernel build may run without the mind's venv).
"""

from __future__ import annotations

import argparse
import base64
import binascii
import sys
from pathlib import Path

NAME_MAX = 39  # AuthorizedKey::kNameMax less the null


class KeyError_(Exception):
    pass


def parse(text: str, where: str) -> list[tuple[bytes, str]]:
    keys: list[tuple[bytes, str]] = []
    for n, line in enumerate(text.splitlines(), 1):
        s = line.strip()
        if not s or s.startswith("#"):
            continue
        parts = s.split(None, 1)
        field = parts[0]
        name = parts[1].strip() if len(parts) > 1 else "unnamed"
        try:
            key = base64.b64decode(field, validate=True)
        except (binascii.Error, ValueError):
            key = b""
        if len(field) != 44 or len(key) != 32 or base64.b64encode(key).decode() != field:
            raise KeyError_(f"{where}:{n}: not a public key (44 characters of base64, as `kilo key show` prints): "
                            f"{field[:50]!r}")
        if any(k == key for k, _ in keys):
            raise KeyError_(f"{where}:{n}: the same key again ({name})")
        keys.append((key, name))
    return keys


def c_name(name: str) -> str:
    safe = "".join(ch if 32 <= ord(ch) < 127 and ch not in '"\\?' else "_" for ch in name)
    return safe[:NAME_MAX]


def render(keys: list[tuple[bytes, str]], source: str) -> str:
    rows = []
    for key, name in keys:
        hexes = ", ".join(f"0x{b:02x}" for b in key)
        rows.append(f'    {{{{{hexes}}}, "{c_name(name)}"}},')
    return "\n".join([
        f"// Generated by kernel/keys/gen_keys.py from {source}: do not edit, do not commit.",
        "#ifndef KILO_KEYS_AUTHORIZED_KEYS_GEN_H",
        "#define KILO_KEYS_AUTHORIZED_KEYS_GEN_H",
        '#include "net/authorized_keys.h"',
        "",
        "static const kilo::AuthorizedKey kAuthorizedKeys[] = {",
        *rows,
        "};",
        f"static const unsigned kAuthorizedKeyCount = {len(keys)};",
        "",
        "#endif",
        "",
    ])


def no_keys_message(shown: str) -> str:
    return f"""
{shown} has no keys, so this kernel would let no laptop in.
On this laptop, once:
    kilo key init                       (makes ~/.config/kilo/host_key and prints its public line)
    kilo key show >> {shown}
then run make -C kernel again (and commit {shown}: it holds public keys only).
To build a kernel for a test with another list instead:
    make -C kernel KILO_AUTHORIZED_KEYS=/path/to/authorized_keys
"""


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("list", type=Path)
    ap.add_argument("out", type=Path)
    ap.add_argument("--shown-as", default=None, help="the list's name in messages")
    a = ap.parse_args()
    shown = a.shown_as or str(a.list)
    try:
        text = a.list.read_text(encoding="utf-8")
    except OSError as e:
        print(f"gen_keys: cannot read {shown}: {e.strerror}", file=sys.stderr)
        return 1
    try:
        keys = parse(text, shown)
    except KeyError_ as e:
        print(f"gen_keys: {e}", file=sys.stderr)
        return 1
    if not keys:
        print(no_keys_message(shown), file=sys.stderr)
        return 1
    out = render(keys, shown)
    a.out.parent.mkdir(parents=True, exist_ok=True)
    if not a.out.exists() or a.out.read_text() != out:
        a.out.write_text(out)
        print(f"  KEYS  {a.out}: {len(keys)} authorized key{'s' if len(keys) != 1 else ''} from {shown}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
